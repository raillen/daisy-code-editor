export {}
const bindings = await Bun.file("internal/config/keybindings.go").text()
const actions = await Bun.file("internal/action/action.go").text()
const pairs = [...bindings.matchAll(/^\s*("(?:[^"\\]|\\.)*"):\s*("[^"]+"),/gm)].map(match => `${match[1]}: ${match[2]}`)
const ids = [...actions.matchAll(/^\s*\w+\s+Action = "([^"]+)"/gm)].map(match => JSON.stringify(match[1]))
await Bun.write("src/core/keymap.ts", `// Generated by scripts/migrate-keymap.ts from the frozen Go reference.\nexport const actionIds = [${ids.join(",\n")}] as const\nexport type ActionId = typeof actionIds[number]\nexport const defaultBindings: Record<string, ActionId> = {\n${pairs.join(",\n")}\n}\n`)
