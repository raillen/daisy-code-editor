import { parse } from "smol-toml"
const locales: Record<string, unknown> = {}
for (const locale of ["pt-BR", "en-US"]) locales[locale] = parse(await Bun.file(`internal/i18n/catalogs/${locale}.toml`).text())
const source = await Bun.file("internal/config/themes.go").text()
const themes: Record<string, unknown> = {}
const snakeCase = (value: string) => value.replace(/([a-z])([A-Z])/g, "$1_$2").replace(/([A-Z])([A-Z][a-z])/g, "$1_$2").toLowerCase()
for (const match of source.matchAll(/\{\s*Name:\s*"([^"]+)"[\s\S]*?(?=\n\t\},)/g)) {
  const name = match[1] ?? ""
  const section = (key: string) => Object.fromEntries([...(match[0].match(new RegExp(`${key}: [^\\{]+\\{([\\s\\S]*?)\\n\\t\\t\\}`))?.[1] ?? "").matchAll(/(\w+):\s*"([^"]+)"/g)].map(pair => [snakeCase(pair[1] ?? ""), pair[2]]))
  themes[name.toLowerCase().replaceAll(" ", "-")] = { name, ui: section("UI"), syntax: section("Syntax") }
}
await Bun.write("src/services/catalogs.ts", `// Generated by scripts/migrate-catalogs.ts from frozen reference catalogs.\nexport const builtInLocales = ${JSON.stringify(locales, null, 2)}\nexport const builtInThemes = ${JSON.stringify(themes, null, 2)}\n`)
